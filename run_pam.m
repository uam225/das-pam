% --- Load the recorded data ---
load('50mm_50mm_ppw15_sim.mat');  % Loads `sensor_data` generated by kWave_simulation.m

% --- Define simulation and array parameters ---
c = 1.5;                % Speed of sound [mm/us] (1500 m/s)
Nx = 1000;              % Grid points along x (use Nx = 667 for PPW = 10 simulations)
Ny = 1000;              % Grid points along y (use Ny = 667 for PPW = 10 simulations)
dx = 100 / Nx;          % Grid spacing [mm]
dt = 0.5 * (dx / c);    % Time step [us] (matches simulation CFL = 0.5 condition)
fprintf('Time step (dt): %.6f µs\n', dt);

% --- Construct grid vectors (covering full 100 mm x 100 mm domain) ---
grid_x = (0:Nx-1) * dx;  % 0 to 99.9 mm
grid_y = (0:Ny-1) * dx;

% --- Reconstruct sensor positions based on simulation setup ---
num_receivers = 64;
x_sensor = linspace(10, 90, num_receivers);  % 10 mm to 90 mm (1.27 mm pitch)
y_sensor = ones(1, num_receivers) * 90;      % All at y = 90 mm
sensor_positions = [x_sensor', y_sensor'];


% --- Call the PCM beamformer ---
tic
[pcm_map, x_scan, y_scan] = generate_pam(sensor_data, sensor_positions, grid_x, grid_y, c, dt);
disp('Beamformer completed')
toc
%%
% --- Visualise the result ---
figure;
imagesc(x_scan, y_scan, pcm_map);
axis image;
xlabel('X [mm]');
ylabel('Y [mm]');
title('Cavitation Map');
colorbar;
set(gca, 'YDir', 'normal');  % Flip Y axis for correct orientation

